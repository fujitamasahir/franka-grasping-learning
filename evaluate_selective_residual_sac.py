"""Run an actual episode-level selective BC + residual SAC controller.

The gate chooses BC or BC+SAC ONCE, immediately after reset, from the
observed initial cube (x, y) position. It never sees outcome labels,
future observations, or counterfactual rollouts. Use a frozen gate JSON
generated by analyze_selective_residual_gate.py.

Run with mjpython on macOS (MuJoCo viewer environment).
"""

import argparse
import csv
import json
from pathlib import Path

import numpy as np
from stable_baselines3 import SAC

from analyze_selective_residual_gate import gate_uses_sac
from franka_bc_residual_env import BCResidualEnv


def run_episode(env, sac_model, gate, mode, seed):
    obs, _ = env.reset(seed=seed)
    cube_x = float(env.env.cube_x)
    cube_y = float(env.env.cube_y)
    use_sac = gate_uses_sac(gate, mode, cube_x, cube_y)

    steps = 0
    max_lift = 0.0
    total_residual = 0.0
    while True:
        if use_sac:
            action, _ = sac_model.predict(obs, deterministic=True)
        else:
            action = np.zeros(3, dtype=np.float32)
        obs, _, terminated, truncated, info = env.step(action)
        steps += 1
        max_lift = max(max_lift, float(info["lift_height"]))
        total_residual += float(info["residual_norm"])
        if terminated or truncated:
            break

    return {
        "seed": seed,
        "cube_x": cube_x,
        "cube_y": cube_y,
        "mode": mode,
        "uses_sac": int(use_sac),
        "success": int(info["is_success"]),
        "steps": steps,
        "max_lift": max_lift,
        "mean_residual_m": total_residual / steps,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gate-config", required=True)
    parser.add_argument("--mode", choices=("safety", "balanced"), default="safety")
    parser.add_argument("--bc-model", default="bc_models/fair_wide_expert_seed42.pt")
    parser.add_argument(
        "--sac-model", default="bc_residual_sac_runs/C_hard_shaped_seed456/best_model.zip"
    )
    parser.add_argument("--position-range", type=float, default=0.20)
    parser.add_argument("--residual-meters", type=float, default=0.005)
    parser.add_argument("--episodes", type=int, default=20)
    parser.add_argument("--seed", type=int, default=160000)
    parser.add_argument("--output", default="bc_results/selective_gate_live_smoke.csv")
    parser.add_argument(
        "--paired-reference",
        default=None,
        help="Optional paired BC/SAC CSV for verifying exact gated outcomes by seed",
    )
    args = parser.parse_args()
    if args.episodes < 1:
        parser.error("--episodes must be positive")
    with Path(args.gate_config).open(encoding="utf-8") as file:
        gate = json.load(file)
    if gate.get("schema_version") != 1:
        raise ValueError("Unsupported gate config")

    model = SAC.load(args.sac_model, device="cpu")
    env = BCResidualEnv(
        bc_model=args.bc_model,
        position_range=args.position_range,
        residual_meters=args.residual_meters,
    )
    rows = []
    try:
        for i in range(args.episodes):
            result = run_episode(env, model, gate, args.mode, args.seed + i)
            rows.append(result)
            print(
                f"{i + 1}/{args.episodes} seed={result['seed']} "
                f"policy={'SAC' if result['uses_sac'] else 'BC'} "
                f"success={result['success']}"
            )
    finally:
        env.close()

    if args.paired_reference:
        from analyze_selective_residual_gate import load_pairs
        reference = load_pairs(args.paired_reference)
        for row in rows:
            seed = row["seed"]
            if seed not in reference:
                raise ValueError(f"Seed {seed} missing from paired reference")
            expected = reference[seed]
            if not np.isclose(row["cube_x"], expected["cube_x"], atol=1e-9):
                raise AssertionError(f"Cube x mismatch for seed {seed}")
            if not np.isclose(row["cube_y"], expected["cube_y"], atol=1e-9):
                raise AssertionError(f"Cube y mismatch for seed {seed}")
            expected_success = expected["sac"] if row["uses_sac"] else expected["bc"]
            if row["success"] != expected_success:
                raise AssertionError(
                    f"Seed {seed}: live success {row['success']} != "
                    f"paired counterfactual {expected_success}"
                )
        print("Live outcomes match the selected paired rollouts.")

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)

    success = sum(row["success"] for row in rows)
    used = sum(row["uses_sac"] for row in rows)
    print(f"Success: {success}/{len(rows)} ({success / len(rows):.1%})")
    print(f"SAC activated: {used}/{len(rows)} ({used / len(rows):.1%})")
    print(f"Saved: {output}")


if __name__ == "__main__":
    main()
